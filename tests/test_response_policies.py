"""Opponent response policies on SYNTHETIC frame states.

The states below are generated from a seeded random number generator. They are not match
observations; they exist to test invariances and constraints deterministically.
"""

from __future__ import annotations

import numpy as np
import pytest

from footymind.counterfactual.response import (
    MIN_SEPARATION_M,
    PITCH_MARGIN_M,
    POLICY_NAMES,
    Intervention,
    ResponseContext,
    apply_response,
    policy_info,
)
from footymind.counterfactual.response_model import (
    FEATURES_X,
    FEATURES_Y,
    ResponseModel,
    features,
)
from footymind.spatial.state import FrameState
from footymind.tracking.model import PitchSpec, Provenance

CARRIER = 9  # home_9
RECEIVER = 7  # home_7
NAN_POS = 20  # away_20: not on the pitch
NAN_VEL = 15  # away_15: velocity unavailable


def synthetic_state(seed: int = 0, sign: int = 1) -> FrameState:
    """22 players: home attacks +x (sign=+1). Index 0 / 11 are the goalkeepers."""
    rng = np.random.default_rng(seed)
    xy = np.column_stack([rng.uniform(-40, 40, 22), rng.uniform(-28, 28, 22)])
    xy[0] = [-50.0, 0.0]
    xy[11] = [50.0, 0.0]
    vel = rng.normal(0, 2.5, (22, 2))
    xy[NAN_POS] = np.nan
    vel[NAN_POS] = np.nan
    vel[NAN_VEL] = np.nan
    ball = xy[CARRIER] + [0.3, 0.0]
    is_gk = np.zeros(22, dtype=bool)
    is_gk[[0, 11]] = True
    s = FrameState(
        match_id="synthetic",
        frame=1,
        period=1,
        time_s=0.0,
        player_ids=[f"home_{i}" for i in range(11)] + [f"away_{i}" for i in range(11, 22)],
        teams=["home"] * 11 + ["away"] * 11,  # type: ignore[list-item]
        jerseys=list(range(22)),
        xy=xy,
        vel=vel,
        is_gk=is_gk,
        ball=ball,
        attacking_team="home",
        possession_id="p1",
        carrier=CARRIER,
        attack_sign=1,
        position_provenance=[Provenance.OBSERVED] * 22,
        velocity_provenance=[Provenance.DERIVED] * 22,
    )
    return mirror(s) if sign == -1 else s


def mirror(s: FrameState) -> FrameState:
    m = s.copy()
    m.xy[:, 0] *= -1
    m.vel[:, 0] *= -1
    m.ball = s.ball * np.array([-1.0, 1.0])
    m.attack_sign = -s.attack_sign
    return m


def synthetic_model() -> ResponseModel:
    """A response model fit on synthetic rows generated by a known smooth rule."""
    rng = np.random.default_rng(42)
    n = 4000
    p = np.column_stack([rng.uniform(-40, 40, n), rng.uniform(-30, 30, n)])
    v = rng.normal(0, 2.5, (n, 2))
    ball = rng.uniform(-30, 30, (n, 2))
    xx = np.empty((n, len(FEATURES_X)))
    xy = np.empty((n, len(FEATURES_Y)))
    for i in range(n):
        a, b = features(p[i : i + 1], v[i : i + 1], ball[i], np.zeros(2), ball[i : i + 1], 52.5)
        xx[i], xy[i] = a[0], b[0]
    offsets = [0.5, 1.0]
    disp = np.stack([v * h + 0.05 * (ball - p) * h for h in offsets], axis=1)
    return ResponseModel.fit(xx, xy, disp, offsets, meta={"synthetic": True})


MODEL = synthetic_model()


def ctx(**kw: object) -> ResponseContext:
    base: dict[str, object] = {
        "pitch": PitchSpec(),
        "horizon_s": 1.5,
        "ball_velocity": np.array([1.0, -0.5]),
        "model": MODEL,
    }
    base.update(kw)
    return ResponseContext(**base)  # type: ignore[arg-type]


def run(state: FrameState, ivs: list[Intervention], policy: str, c: ResponseContext | None = None):
    hyp = state.copy()
    for iv in ivs:
        i = state.index(iv.player_id)
        d = np.array([iv.x, iv.y]) - hyp.xy[i]
        hyp.xy[i] = [iv.x, iv.y]
        hyp.position_provenance[i] = Provenance.HYPOTHETICAL
        if i == state.carrier:
            hyp.ball = hyp.ball + d
    moves, notes = apply_response(state, hyp, ivs, policy, c or ctx())
    return hyp, moves, notes


def shift(state: FrameState, idx: int, dx: float, dy: float) -> Intervention:
    return Intervention(state.player_ids[idx], state.xy[idx, 0] + dx, state.xy[idx, 1] + dy)


TRIGGER = {
    "marker_follows": RECEIVER,
    "press_carrier": CARRIER,
    "zonal_shift": CARRIER,
    "lane_cover": RECEIVER,
    "learned": CARRIER,
}


@pytest.mark.parametrize("policy", list(TRIGGER))
def test_policies_move_only_eligible_defenders(policy: str) -> None:
    s = synthetic_state()
    who = TRIGGER[policy]
    iv = shift(s, who, 4.0, 3.0)
    hyp, moves, _ = run(s, [iv], policy)
    assert moves, f"{policy} produced no move for a 5 m intervention"
    for m in moves:
        j = s.index(m.player_id)
        assert m.provenance == Provenance.SIMULATED and m.reason
        assert s.teams[j] == "away"  # attackers are never auto-moved
        assert not s.is_gk[j] or policy == "marker_follows"
        assert m.player_id != iv.player_id
        assert j != NAN_POS
        assert hyp.position_provenance[j] == Provenance.SIMULATED
    # untouched players keep their observed positions exactly
    moved = {s.index(m.player_id) for m in moves} | {who}
    for j in range(22):
        if j not in moved:
            np.testing.assert_array_equal(hyp.xy[j], s.xy[j])


@pytest.mark.parametrize(
    "policy", [p for p in POLICY_NAMES if p != "learned_innovation"]
)  # learned_innovation: own model-backed mirror test
def test_mirror_invariance(policy: str) -> None:
    """Mirror x -> -x with the attack direction flipped: the moves are mirrored."""
    s = synthetic_state(seed=3)
    m = mirror(s)
    who = TRIGGER.get(policy, CARRIER)
    _, moves, _ = run(s, [shift(s, who, 3.0, -2.0)], policy)
    bv = np.array([-1.0, -0.5])  # mirrored ball velocity
    _, moves_m, _ = run(m, [shift(m, who, -3.0, -2.0)], policy, ctx(ball_velocity=bv))
    assert [mv.player_id for mv in moves] == [mv.player_id for mv in moves_m]
    for a, b in zip(moves, moves_m, strict=True):
        np.testing.assert_allclose(b.to_xy, (-a.to_xy[0], a.to_xy[1]), atol=1e-6)


@pytest.mark.parametrize(
    "policy", [p for p in POLICY_NAMES if p not in ("none", "learned_innovation")]
)  # learned_innovation: own model-backed tests in test_learned_innovation_policy.py
@pytest.mark.parametrize("seed", [0, 1, 2])
def test_small_intervention_small_response(policy: str, seed: int) -> None:
    s = synthetic_state(seed=seed)
    who = TRIGGER[policy]
    _, moves, _ = run(s, [shift(s, who, 0.06, 0.08)], policy)  # 0.1 m
    for mv in moves:
        d = np.hypot(mv.to_xy[0] - mv.from_xy[0], mv.to_xy[1] - mv.from_xy[1])
        assert d <= 0.1 + 1e-6, (policy, mv.player_id, d)


def test_none_and_untriggered_policies_do_nothing() -> None:
    s = synthetic_state()
    _, moves, _ = run(s, [shift(s, CARRIER, 3.0, 0.0)], "none")
    assert moves == []
    # press/zonal need the carrier (ball) to move; lane_cover needs a non-carrier attacker
    for pol, who in [
        ("press_carrier", RECEIVER),
        ("zonal_shift", RECEIVER),
        ("lane_cover", CARRIER),
    ]:
        _, moves, notes = run(s, [shift(s, who, 3.0, 0.0)], pol)
        assert moves == [] and notes
    # moving a defender triggers no rule response
    _, moves, _ = run(s, [shift(s, 13, 2.0, 0.0)], "press_carrier")
    assert moves == []


def test_moves_respect_envelope_bounds_and_separation() -> None:
    s = synthetic_state(seed=5)
    hl, hw = 52.5 + PITCH_MARGIN_M, 34.0 + PITCH_MARGIN_M
    for pol in ("press_carrier", "zonal_shift", "lane_cover", "learned"):
        who = TRIGGER[pol]
        hyp, moves, _ = run(s, [shift(s, who, 15.0, 10.0)], pol)
        for mv in moves:
            j = s.index(mv.player_id)
            assert abs(mv.to_xy[0]) <= hl + 1e-9 and abs(mv.to_xy[1]) <= hw + 1e-9
            others = np.delete(hyp.xy, j, axis=0)
            assert np.nanmin(np.linalg.norm(others - hyp.xy[j], axis=1)) >= MIN_SEPARATION_M - 1e-6
            # a differential move is at most the envelope's diameter (radius ~ 2.7 m from rest)
            assert np.hypot(mv.to_xy[0] - mv.from_xy[0], mv.to_xy[1] - mv.from_xy[1]) < 12.0


def test_separation_resolved_deterministically() -> None:
    s = synthetic_state(seed=6)
    # Put an attacker right where the presser wants to go: the move must be shortened.
    s.xy[RECEIVER] = s.xy[CARRIER] + [2.0, 0.0]
    a = run(s, [shift(s, CARRIER, 1.0, 0.0)], "press_carrier")
    b = run(s, [shift(s, CARRIER, 1.0, 0.0)], "press_carrier")
    assert [(m.player_id, m.to_xy) for m in a[1]] == [(m.player_id, m.to_xy) for m in b[1]]


def test_nan_velocity_defender_uses_rest_envelope_and_says_so() -> None:
    s = synthetic_state(seed=0)
    s.xy[NAN_VEL] = s.xy[CARRIER] + [3.0, 3.0]  # make it the nearest defender
    _, moves, _ = run(s, [shift(s, CARRIER, -3.0, 2.0)], "press_carrier")
    assert len(moves) == 1 and moves[0].player_id == s.player_ids[NAN_VEL]
    assert "velocity unavailable" in moves[0].reason


def test_learned_without_model_is_an_error() -> None:
    s = synthetic_state()
    with pytest.raises(ValueError):
        run(s, [shift(s, CARRIER, 2.0, 0.0)], "learned", ctx(model=None))


def test_response_model_json_round_trip_and_mirror_structure() -> None:
    m2 = ResponseModel.from_json(MODEL.to_json())
    rng = np.random.default_rng(0)
    xx, xy = rng.normal(size=(5, len(FEATURES_X))), rng.normal(size=(5, len(FEATURES_Y)))
    np.testing.assert_allclose(m2.predict_all(xx, xy), MODEL.predict_all(xx, xy))
    # y displacement is odd in the y-type features
    np.testing.assert_allclose(MODEL.predict(xx, -xy, 1)[:, 1], -MODEL.predict(xx, xy, 1)[:, 1])
    assert MODEL.offset_index(5.0) == 1 and MODEL.offset_index(0.4) == 0


def test_policy_info_contract() -> None:
    for name in POLICY_NAMES:
        info = policy_info(name, "metrica")
        assert info.name == name and info.description and info.assumptions
        if name not in ("learned", "learned_innovation"):
            assert info.validated is False and info.validation_ref is None
        if not info.validated and name != "none":
            assert info.status.startswith("experimental")
