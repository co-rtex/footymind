"""Failure-mode analysis for RQ1 v2: where does spatial context help, and where do models fail?

Joins the committed experiment's out-of-fold predictions
(``experiments/results/pass_outcome_v2_3match/oof_predictions.parquet``, regenerated by
re-running that config) with decision-time context from the pass dataset, then reports
per context: n, completion rate, log loss of A (event) and B (spatial), and Δ (B − A)
with a possession-clustered bootstrap CI.

Run with ``python -m footymind.research.failure_modes``.
"""

from __future__ import annotations

import json
from typing import Any

import numpy as np
import polars as pl

from footymind.data.store import git_revision
from footymind.paths import EXPERIMENTS_DIR
from footymind.research.pass_dataset import DatasetConfig, build

EPS = 1e-4
NAME = "pass_outcome_v2_3match"


def _ll(y: np.ndarray, p: np.ndarray) -> np.ndarray:
    p = np.clip(p, EPS, 1 - EPS)
    return -(y * np.log(p) + (1 - y) * np.log(1 - p))


def contexts(df: pl.DataFrame) -> dict[str, pl.Expr]:
    return {
        "all": pl.lit(True),
        "short (<12 m to candidate)": pl.col("cand_distance_m") < 12,
        "medium (12-25 m)": pl.col("cand_distance_m").is_between(12, 25),
        "long (>25 m)": pl.col("cand_distance_m") > 25,
        "under pressure (defender <3 m)": pl.col("press_nearest_def_m") < 3,
        "no pressure (>=6 m)": pl.col("press_nearest_def_m") >= 6,
        "forward (release cos > 0.5)": pl.col("release_cos") > 0.5,
        "backward (release cos < -0.5)": pl.col("release_cos") < -0.5,
        "final third (ball x_att > 17.5)": pl.col("ball_x_att") > 17.5,
        "own third (ball x_att < -17.5)": pl.col("ball_x_att") < -17.5,
        "restart (set piece)": pl.col("is_restart") == 1,
        "header": pl.col("is_head") == 1,
        "misaligned (candidate > 20° off release)": pl.col("cand_angle_dev") > np.deg2rad(20),
    }


def main(n_boot: int = 2000, seed: int = 0) -> None:
    res_dir = EXPERIMENTS_DIR / "results" / NAME
    cfg = json.loads((res_dir / "results.json").read_text())
    oof = pl.read_parquet(res_dir / "oof_predictions.parquet")
    ds = build(cfg["config"]["matches"], DatasetConfig(**cfg["config"].get("dataset", {})))
    df = ds.join(oof.select("match_id", "event_id", "p_A_logreg", "p_B_logreg"),
                 on=["match_id", "event_id"], how="inner")
    if df.height != oof.height:
        raise RuntimeError(f"join mismatch: {df.height} vs {oof.height}")
    rng = np.random.default_rng(seed)
    out: list[dict[str, Any]] = []
    for name, expr in contexts(df).items():
        sub = df.filter(expr)
        if sub.height < 30:
            continue
        y = sub["success"].to_numpy().astype(float)
        la = _ll(y, sub["p_A_logreg"].to_numpy())
        lb = _ll(y, sub["p_B_logreg"].to_numpy())
        d = lb - la
        groups = (sub["match_id"] + "|" + sub["possession_id"].fill_null("none")).to_numpy()
        uniq, inv = np.unique(groups, return_inverse=True)
        members = [np.flatnonzero(inv == g) for g in range(uniq.size)]
        boots = []
        for _ in range(n_boot):
            idx = np.concatenate([members[g] for g in rng.integers(0, uniq.size, uniq.size)])
            boots.append(d[idx].mean())
        out.append({
            "context": name, "n": int(sub.height), "completion_rate": float(y.mean()),
            "log_loss_A": float(la.mean()), "log_loss_B": float(lb.mean()),
            "delta_B_minus_A": float(d.mean()),
            "ci95": [float(np.percentile(boots, 2.5)), float(np.percentile(boots, 97.5))],
        })
    result = {"name": "failure_modes_v2", "source_experiment": NAME,
              "source_code_revision": cfg["code_revision"], "code_revision": git_revision(),
              "contexts": out}
    (res_dir / "failure_modes.json").write_text(json.dumps(result, indent=2))
    for r in out:
        print(f"{r['context']:45s} n={r['n']:5d} rate={r['completion_rate']:.2f} "
              f"A={r['log_loss_A']:.3f} B={r['log_loss_B']:.3f} Δ={r['delta_B_minus_A']:+.3f} "
              f"[{r['ci95'][0]:+.3f}, {r['ci95'][1]:+.3f}]")


if __name__ == "__main__":
    main()
